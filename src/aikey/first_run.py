"""Fresh-directory AI Key preparation using the existing config/provider machinery.

No network, service, trust import, model installation or camera-policy mutation.
An exclusive new directory is the admission marker. Partial failures deliberately
remain for inspection: never reuse, reset or repair a possibly adopted identity.
"""

import ipaddress
import json
import os
from pathlib import Path
import stat
import time

from .config import ConfigError, atomic_private, defaults, initialize, validate_config
from .protocol import classify_controller_version
from .providers import validate_inference_config


def trust_target(config, channel, fingerprint, port=None):
    """Resolve only a declared channel/pin, without network or configuration writes."""
    if channel not in {"control", "search"} or not isinstance(fingerprint, str):
        raise ConfigError("Invalid controller trust channel or fingerprint")
    controller = config["controller"]
    if not controller.get("host"):
        raise ConfigError("Set controller.host before importing trust")
    search = channel == "search"
    if search and not controller.get("search_ca_file"):
        raise ConfigError("Search trust requires a separately configured search CA path and pin")
    pin = controller.get("search_expected_fingerprint" if search else "expected_fingerprint")
    if pin is not None and (not isinstance(pin, str)
            or pin.replace(":", "").lower() != fingerprint.replace(":", "").lower()):
        raise ConfigError("Supplied fingerprint differs from the selected channel's configured pin")
    selected_port = port if port is not None else controller["search_port" if search else "control_port"]
    if type(selected_port) is not int or not 1 <= selected_port <= 65535:
        raise ConfigError("Trust endpoint must be a TCP port between 1 and 65535")
    return controller["host"], selected_port, Path(controller["search_ca_file" if search else "ca_file"])


def prepare(args, inference):
    requested = args.directory.expanduser().absolute()
    # Resolve only the parent: resolving the leaf would follow an existing link.
    root = requested.parent.resolve(strict=True) / requested.name
    config_path, state = root / "config.json", root / "state"
    if not args.controller:
        raise ConfigError("Setup requires a controller hostname or IP")
    _, evidence = classify_controller_version(args.protect_version)
    if evidence == "unrecognized_format":
        raise ConfigError("Protect version must be a numeric dotted version")
    if args.ffmpeg_path is not None and not args.ffmpeg_path.is_absolute():
        raise ConfigError("--ffmpeg-path must be absolute in the eventual runtime")
    factory_seconds = getattr(args, "factory_enrollment_seconds", 0)
    if type(factory_seconds) is not int or not 0 <= factory_seconds <= 600:
        raise ConfigError("Factory enrollment duration must be an integer from 0 to 600 seconds")
    if factory_seconds and not args.controller_fingerprint:
        raise ConfigError("Factory enrollment requires an independently verified controller SHA-256 pin")
    # Schema-only placeholder, never persisted. Real identity is generated by
    # initialize only after all settings pass the same normal validators.
    config = defaults(state, "020000000000")
    config["controller"].update(host=args.controller, protect_version=args.protect_version,
                                control_profile=args.control_profile)
    config["device"]["ip"] = args.device_ip
    linux_discovery = getattr(args, "linux_discovery", False)
    if linux_discovery:
        try:
            peers = [ipaddress.IPv4Address(value) for value in (args.controller, args.device_ip)]
        except ipaddress.AddressValueError:
            raise ConfigError("Linux discovery requires literal controller and device IPv4 addresses") from None
        if any(ip.is_unspecified or ip.is_multicast or ip.is_loopback or ip.is_reserved
               or not ip.is_private for ip in peers):
            raise ConfigError("Linux discovery requires concrete private LAN IPv4 addresses")
        config["discovery"].update(enabled=True, bind="0.0.0.0", port=10001,
                                   multicast=True, interface_ip=str(peers[1]),
                                   allowed_controller_ips=[str(peers[0])])
    if factory_seconds:
        config["device"]["factory_enrollment_until"] = int(time.time()) + factory_seconds
    config["runtime"].update(bind=args.bind or args.device_ip, https_port=args.https_port)
    if args.controller_fingerprint:
        config["controller"]["expected_fingerprint"] = args.controller_fingerprint
    if args.search_fingerprint:
        config["controller"]["search_expected_fingerprint"] = args.search_fingerprint
        config["controller"]["search_ca_file"] = str(state / "controller-search-ca.pem")
    for value in (args.controller_fingerprint, args.search_fingerprint):
        if value is None:
            continue
        pin = value.replace(":", "")
        if len(pin) != 64 or any(c not in "0123456789abcdefABCDEF" for c in pin):
            raise ConfigError("Controller fingerprint must be a SHA-256 pin")
    if args.pin_only_hostname:
        config["controller"]["verify_hostname"] = False
    config["inference"] = inference
    if args.ffmpeg_path is not None:
        config["worker"]["ffmpeg_path"] = str(args.ffmpeg_path)
    config["worker"]["request_mp4_exports"] = args.request_mp4_exports
    for argument, field, maximum in (("worker_timeout_seconds", "timeout_s", 600),
                                    ("caption_timeout_seconds", "caption_timeout_s", 600),
                                    ("max_images", "max_images", 16)):
        value = getattr(args, argument, None)
        if value is not None:
            if type(value) is not int or not 1 <= value <= maximum:
                raise ConfigError(f"{argument} must be an integer from 1 to {maximum}")
            config["worker"][field] = value
    if config["worker"].get("caption_timeout_s", 30) > config["worker"]["timeout_s"]:
        raise ConfigError("Caption timeout must not exceed worker timeout")
    config = validate_config(config, base=root)
    validate_inference_config(config["inference"], lab=False, require_api_key=False)
    try:
        root.mkdir(mode=0o700)
    except FileExistsError as exc:
        raise ConfigError("Setup directory already exists; existing or partial installations are never reused") from exc
    # Harden only this exclusively created directory, before any identity exists.
    # Some NAS filesystems do not preserve the requested creation mode.
    info = root.lstat()
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.geteuid():
        raise ConfigError("Setup directory must be owned by this user with mode 700; inspect retained directory")
    descriptor = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        opened = os.fstat(descriptor)
        if (opened.st_dev, opened.st_ino) != (info.st_dev, info.st_ino):
            raise ConfigError("Setup directory changed; inspect retained directory")
        os.fchmod(descriptor, 0o700)
        secured = os.fstat(descriptor)
        current = root.lstat()
        if (stat.S_IMODE(secured.st_mode) != 0o700
                or (current.st_dev, current.st_ino) != (info.st_dev, info.st_ino)):
            raise ConfigError("Setup directory is not private; inspect retained directory")
    finally:
        os.close(descriptor)
    generated = initialize(config_path, state, controller_host=args.controller,
                           device_ip=args.device_ip)
    config["device"]["mac"] = generated["device"]["mac"]
    config = validate_config(config, base=root)
    atomic_private(config_path, json.dumps(config, indent=2) + "\n")
    return {"configuration": str(config_path), "state": str(state),
            "setup_complete": True, "network_contacted": False,
            "service_started": False, "controller_trust_imported": False,
            "adoption": "not_started", "model_availability": "not_tested",
            "operator_reported_version_evidence": evidence,
            "vision_destination": config["inference"]["base_url"],
            "media_policy": "Selected frames go to this endpoint only when inference is explicitly started; upstream forwarding and retention are not verified",
            "additional_features_enabled": linux_discovery,
            "discovery_enabled": linux_discovery,
            "factory_enrollment_until": config["device"].get("factory_enrollment_until", 0),
            "next_steps": ["Provision the referenced private provider key if required",
                           "Import controller trust using an independently verified fingerprint",
                           "Run local-aikey check with the generated configuration",
                           "Review camera scope, media destination and cost before explicitly running and adopting"]}
